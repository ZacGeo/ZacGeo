"""Generate a GitHub profile statistics SVG from public GitHub REST API data."""
import json
import os
from pathlib import Path
from urllib.request import Request, urlopen
from html import escape

USERNAME = os.environ.get('PROFILE_USERNAME', 'ZacGeo')
TOKEN = os.environ.get('GITHUB_TOKEN', '')
ROOT = Path(__file__).resolve().parents[1]


def api(path):
    headers = {'Accept': 'application/vnd.github+json', 'User-Agent': 'ZacGeo-profile-readme'}
    if TOKEN:
        headers['Authorization'] = f'Bearer {TOKEN}'
    request = Request('https://api.github.com' + path, headers=headers)
    with urlopen(request, timeout=30) as response:
        return json.load(response)


def card(repos, stars, followers):
    cells = [('PUBLIC REPOS', str(repos), '#54a0ff'),
             ('TOTAL STARS', str(stars), '#43e0cb'),
             ('FOLLOWERS', str(followers), '#24c5e6')]
    svg = ['''<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="245" viewBox="0 0 1000 245"><defs><linearGradient id="bg"><stop stop-color="#063e39"/><stop offset="1" stop-color="#103445"/></linearGradient><style>.t{font-family:ui-monospace,Consolas,monospace}.blink{animation:blink 2.8s ease-in-out infinite}@keyframes blink{50%{opacity:.3}}</style></defs><rect x="1" y="1" width="998" height="243" rx="22" fill="url(#bg)" stroke="#1ad8bd" stroke-width="2"/><rect x="24" y="22" width="952" height="202" rx="18" fill="#081f23" stroke="#148f8b"/><text x="46" y="68" fill="#e4fff7" font-family="Arial" font-weight="bold" font-size="32">Profile Signal</text><text x="47" y="93" fill="#63dbcf" class="t" font-size="14">Public GitHub stats · generated by GitHub Actions</text>''']
    for i,(label,value,color) in enumerate(cells):
        x=45+i*315
        svg.append(f'<rect x="{x}" y="113" width="284" height="94" rx="15" fill="#061a21" stroke="#149b95"/>')
        svg.append(f'<text x="{x+21}" y="141" font-size="14" class="t" fill="#aafcf0">{escape(label)}</text>')
        svg.append(f'<text x="{x+21}" y="185" font-family="Arial" font-weight="bold" font-size="38" fill="{color}">{escape(value)}</text>')
        svg.append(f'<circle class="blink" cx="{x+252}" cy="143" r="5" fill="{color}"/>')
    svg.append('</svg>')
    return ''.join(svg)


def main():
    user = api('/users/' + USERNAME)
    stars = 0
    page = 1
    while True:
        chunk = api(f'/users/{USERNAME}/repos?per_page=100&page={page}&type=owner')
        stars += sum(r['stargazers_count'] for r in chunk if not r.get('fork',False))
        if len(chunk) < 100:
            break
        page += 1
    (ROOT / 'assets' / 'stats.svg').write_text(card(user['public_repos'], stars, user['followers']), encoding='utf-8')
    print(f"Generated stats for {USERNAME}: {user['public_repos']} public repos, {stars} stars, {user['followers']} followers")

if __name__ == '__main__':
    main()
